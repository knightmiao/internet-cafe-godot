WHITE = (255, 255, 255, 255)
CLEAR = (0, 0, 0, 0)


def render(rows: list[str]) -> Image.Image:
    size = len(rows)
    image = Image.new("RGBA", (size, size), CLEAR)
    px = image.load()
    for y, row in enumerate(rows):
        if len(row) != size:
            raise ValueError(f"第 {y} 行宽度 {len(row)} 与画布 {size} 不符：{row!r}")
        for x, ch in enumerate(row):
            if ch == "#":
                px[x, y] = WHITE
    return image


def save_preview(icons: dict[str, Image.Image]) -> None:
    """深墨底上放大 6 倍拼版，模拟 icon 被调制成深色后压在键帽上的观感。"""
    scale, gap, cols = 6, 8, 6
    cell = 10 * scale
    rows = (len(icons) + cols - 1) // cols
    width = gap + cols * (cell + gap)
    height = gap + rows * (cell + gap)
    sheet = Image.new("RGBA", (width, height), (207, 197, 168, 255))
    for index, image in enumerate(icons.values()):
        big = image.resize((image.width * scale, image.height * scale), Image.Resampling.NEAREST)
        # 白剪影在浅底上看不见，预览时染成键帽文字色
        inked = Image.new("RGBA", big.size, (42, 36, 25, 255))
        inked.putalpha(big.getchannel("A"))
        col, row = index % cols, index // cols
        x = gap + col * (cell + gap) + (cell - big.width) // 2
        y = gap + row * (cell + gap) + (cell - big.height) // 2
        sheet.alpha_composite(inked, (x, y))
    PREVIEW.parent.mkdir(parents=True, exist_ok=True)
    sheet.save(PREVIEW)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    icons: dict[str, Image.Image] = {}
    for name, rows in {**ACTIONS, **MODULES, **TRANSPORT}.items():
        image = render(rows)
        image.save(OUT_DIR / f"{name}.png")
        icons[name] = image
    print(f"generated {len(icons)} icons -> {OUT_DIR.relative_to(ROOT)}")
    save_preview(icons)
    print(f"preview   {PREVIEW.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
